#!/usr/bin/env python3
"""List Soundboard_SanityCapped/Sounds/*.mp3 in SoundData.lua.

The MP3s are shipped as they are, so there is nothing to convert: this only
writes the table the addon reads and a manifest for the release notes.
See README.md for the naming rules. No dependencies.
"""

import json
import sys
from pathlib import Path

from naming import sound_name

HERE = Path(__file__).resolve().parent
PACK_DIR = HERE.parent / "Soundboard_SanityCapped"
SOUND_DIR = PACK_DIR / "Sounds"
LUA_OUT = PACK_DIR / "SoundData.lua"
MANIFEST = HERE / "sound_manifest.json"


# --- mp3 --------------------------------------------------------------------

# Bitrates in kbps for Layer III, by header index.
BITRATES_V1 = (0, 32, 40, 48, 56, 64, 80, 96, 112, 128, 160, 192, 224, 256, 320)
BITRATES_V2 = (0, 8, 16, 24, 32, 40, 48, 56, 64, 80, 96, 112, 128, 144, 160)
SAMPLE_RATES = {3: (44100, 48000, 32000), 2: (22050, 24000, 16000), 0: (11025, 12000, 8000)}


def frame_at(data, i):
    """(length_in_bytes, seconds) of the Layer III frame starting at i, or None."""
    if i + 4 > len(data) or data[i] != 0xFF or data[i + 1] & 0xE0 != 0xE0:
        return None
    version = (data[i + 1] >> 3) & 3   # 3 = MPEG1, 2 = MPEG2, 0 = MPEG2.5
    layer = (data[i + 1] >> 1) & 3     # 1 = Layer III
    bitrate_index = (data[i + 2] >> 4) & 0xF
    rate_index = (data[i + 2] >> 2) & 3
    padding = (data[i + 2] >> 1) & 1
    if version == 1 or layer != 1 or bitrate_index in (0, 15) or rate_index == 3:
        return None

    mpeg1 = version == 3
    bitrate = (BITRATES_V1 if mpeg1 else BITRATES_V2)[bitrate_index] * 1000
    rate = SAMPLE_RATES[version][rate_index]
    length = (144 if mpeg1 else 72) * bitrate // rate + padding
    return length, (1152 if mpeg1 else 576) / rate


def audio_start(data):
    """Skip a leading ID3v2 tag, whose size is four 7-bit bytes."""
    if data[:3] != b"ID3" or len(data) < 10:
        return 0
    size = (data[6] << 21) | (data[7] << 14) | (data[8] << 7) | data[9]
    return 10 + size + (10 if data[5] & 0x10 else 0)


def duration(path):
    """Seconds of audio, found by walking every frame; 0 if it is not an MP3."""
    data = path.read_bytes()
    start = audio_start(data)

    # The first sync has to be followed by another frame, or random bytes pass.
    for i in range(start, min(len(data), start + 4096)):
        first = frame_at(data, i)
        if first and (i + first[0] >= len(data) or frame_at(data, i + first[0])):
            break
    else:
        return 0.0

    seconds = 0.0
    while (frame := frame_at(data, i)):
        seconds += frame[1]
        i += frame[0]
    return seconds


# --- lua output -------------------------------------------------------------

def lua_string(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')


def write_lua(entries):
    out = [
        "-- GENERATED BY tools/build_sounds.py -- DO NOT EDIT BY HAND.",
        "-- Add or remove MP3s in Sounds/ and re-run the script.",
        "",
        "local ADDON, ns = ...",
        "",
        "-- Resolved from the folder name at load time, so renaming the addon",
        "-- folder (and its .toc to match) does not need a rebuild.",
        'ns.SOUND_ROOT = "Interface\\\\AddOns\\\\" .. ADDON .. "\\\\Sounds\\\\"',
        "",
        "-- key is the slash command and what is sent to other players.",
        "ns.sounds = {",
    ]
    for e in entries:
        out.append(f'\t{{key = "{lua_string(e["key"])}", name = "{lua_string(e["name"])}", '
                   f'file = "{lua_string(e["file"])}", duration = {e["duration"]}}},')
    out += ["}", ""]
    LUA_OUT.write_text("\n".join(out), encoding="utf-8")


def write_manifest(entries):
    """Machine-readable index of the pack, for CI release notes."""
    MANIFEST.write_text(json.dumps({
        "count": len(entries),
        "sounds": [{"name": e["name"], "command": "/" + e["key"], "file": e["file"],
                    "seconds": e["duration"]} for e in entries],
    }, indent=2) + "\n", encoding="utf-8")


# --- build ------------------------------------------------------------------

def main():
    SOUND_DIR.mkdir(parents=True, exist_ok=True)
    sources = sorted((p for p in SOUND_DIR.iterdir()
                      if p.is_file() and p.suffix.lower() == ".mp3"),
                     key=lambda p: p.stem.lower())

    entries, warnings, used = [], [], {}
    for src in sources:
        name = sound_name(src.stem)
        key = name.lower()
        if not name:
            warnings.append(f"{src.name}: skipped, no letters or digits are left to make a command from")
            continue
        if key in used:
            warnings.append(f"{src.name}: skipped, /{key} is already taken by {used[key]}")
            continue

        seconds = duration(src)
        if not seconds:
            warnings.append(f"{src.name}: skipped, not an MP3 that can be read")
            continue

        used[key] = src.name
        # Soundboard waits this long before the next queued sound, so round up.
        entries.append({"key": key, "name": name, "file": src.name,
                        "duration": round(seconds + 0.5, 1)})
        print(f"  /{key:<24} {seconds:.1f}s, {src.stat().st_size / 1024:.0f} KB")

    write_lua(entries)
    write_manifest(entries)

    print(f"\n{len(entries)} sound(s) in {SOUND_DIR}")
    print(f"Generated {LUA_OUT}")
    if warnings:
        print("\nWarnings:")
        for w in warnings:
            print(f"  ! {w}")
    print("\nRestart WoW (or /reload if the addon was already loaded once).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
